-- DormUp HQ Phase 1
-- Additive business operations schema. Existing CMS/CRM tables and data are preserved.

create extension if not exists "pgcrypto";

create table if not exists public.companies (
  id uuid primary key default gen_random_uuid(),
  name text not null check (btrim(name) <> ''),
  legal_name text,
  tax_id text,
  email text,
  phone text,
  website text,
  address jsonb not null default '{}'::jsonb,
  status text not null default 'prospect' check (status in ('prospect', 'active', 'inactive')),
  owner_id uuid references public.profiles(id) on delete set null,
  tags text[] not null default '{}',
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contacts (
  id uuid primary key default gen_random_uuid(),
  company_id uuid references public.companies(id) on delete set null,
  first_name text,
  last_name text,
  email text,
  phone text,
  job_title text,
  is_primary boolean not null default false,
  status text not null default 'active' check (status in ('active', 'inactive')),
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    nullif(btrim(coalesce(first_name, '')), '') is not null
    or nullif(btrim(coalesce(last_name, '')), '') is not null
    or nullif(btrim(coalesce(email, '')), '') is not null
  )
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  sku text not null unique check (btrim(sku) <> ''),
  name text not null check (btrim(name) <> ''),
  description text,
  kind text not null default 'service' check (kind in ('service', 'subscription', 'addon', 'other')),
  unit text not null default 'item',
  unit_price numeric(14,2) not null default 0 check (unit_price >= 0),
  currency text not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  tax_rate numeric(7,4) not null default 0 check (tax_rate >= 0 and tax_rate <= 100),
  active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.deals (
  id uuid primary key default gen_random_uuid(),
  company_id uuid references public.companies(id) on delete set null,
  primary_contact_id uuid references public.contacts(id) on delete set null,
  lead_id uuid unique references public.leads(id) on delete set null,
  title text not null check (btrim(title) <> ''),
  stage text not null default 'qualified'
    check (stage in ('qualified', 'discovery', 'proposal', 'negotiation', 'won', 'lost')),
  status text not null default 'open' check (status in ('open', 'won', 'lost')),
  value numeric(14,2) not null default 0 check (value >= 0),
  currency text not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  probability smallint not null default 25 check (probability between 0 and 100),
  expected_close_date date,
  closed_at timestamptz,
  lost_reason text,
  owner_id uuid references public.profiles(id) on delete set null,
  source text,
  notes text,
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (status = 'open' and stage not in ('won', 'lost'))
    or (status = 'won' and stage = 'won')
    or (status = 'lost' and stage = 'lost')
  )
);

create table if not exists public.client_projects (
  id uuid primary key default gen_random_uuid(),
  project_number bigint generated by default as identity unique,
  deal_id uuid unique references public.deals(id) on delete set null,
  company_id uuid references public.companies(id) on delete set null,
  primary_contact_id uuid references public.contacts(id) on delete set null,
  case_id uuid unique references public.cases(id) on delete set null,
  name text not null check (btrim(name) <> ''),
  status text not null default 'planned'
    check (status in ('planned', 'active', 'on_hold', 'completed', 'cancelled')),
  health text not null default 'unknown'
    check (health in ('unknown', 'on_track', 'at_risk', 'off_track')),
  priority text not null default 'normal'
    check (priority in ('low', 'normal', 'high', 'urgent')),
  owner_id uuid references public.profiles(id) on delete set null,
  start_date date,
  target_date date,
  completed_at timestamptz,
  budget numeric(14,2) not null default 0 check (budget >= 0),
  currency text not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  progress smallint not null default 0 check (progress between 0 and 100),
  description text,
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (target_date is null or start_date is null or target_date >= start_date)
);

create table if not exists public.project_milestones (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.client_projects(id) on delete cascade,
  title text not null check (btrim(title) <> ''),
  description text,
  status text not null default 'pending'
    check (status in ('pending', 'in_progress', 'completed', 'blocked', 'cancelled')),
  due_date date,
  completed_at timestamptz,
  amount numeric(14,2) check (amount is null or amount >= 0),
  currency text not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  sort_order integer not null default 0,
  owner_id uuid references public.profiles(id) on delete set null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.invoices (
  id uuid primary key default gen_random_uuid(),
  invoice_number text not null unique check (btrim(invoice_number) <> ''),
  company_id uuid not null references public.companies(id) on delete restrict,
  contact_id uuid references public.contacts(id) on delete set null,
  project_id uuid references public.client_projects(id) on delete set null,
  deal_id uuid references public.deals(id) on delete set null,
  status text not null default 'draft'
    check (status in ('draft', 'sent', 'partially_paid', 'paid', 'overdue', 'void')),
  currency text not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  issue_date date not null default current_date,
  due_date date,
  subtotal numeric(14,2) not null default 0 check (subtotal >= 0),
  tax_total numeric(14,2) not null default 0 check (tax_total >= 0),
  discount_total numeric(14,2) not null default 0 check (discount_total >= 0),
  total numeric(14,2) not null default 0 check (total >= 0),
  amount_paid numeric(14,2) not null default 0 check (amount_paid >= 0),
  notes text,
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (due_date is null or due_date >= issue_date),
  check (amount_paid <= total)
);

create table if not exists public.invoice_items (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.invoices(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  description text not null check (btrim(description) <> ''),
  quantity numeric(12,3) not null default 1 check (quantity > 0),
  unit_price numeric(14,2) not null default 0 check (unit_price >= 0),
  tax_rate numeric(7,4) not null default 0 check (tax_rate >= 0 and tax_rate <= 100),
  discount numeric(14,2) not null default 0 check (discount >= 0),
  line_subtotal numeric(14,2) not null default 0 check (line_subtotal >= 0),
  line_tax numeric(14,2) not null default 0 check (line_tax >= 0),
  line_total numeric(14,2) not null default 0 check (line_total >= 0),
  sort_order integer not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid references public.invoices(id) on delete set null,
  company_id uuid not null references public.companies(id) on delete restrict,
  amount numeric(14,2) not null check (amount > 0),
  currency text not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  status text not null default 'pending'
    check (status in ('pending', 'succeeded', 'failed', 'refunded', 'cancelled')),
  method text,
  external_reference text,
  paid_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete restrict,
  contact_id uuid references public.contacts(id) on delete set null,
  product_id uuid references public.products(id) on delete set null,
  project_id uuid references public.client_projects(id) on delete set null,
  status text not null default 'active'
    check (status in ('trialing', 'active', 'paused', 'past_due', 'cancelled', 'ended')),
  amount numeric(14,2) not null check (amount >= 0),
  currency text not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  interval text not null default 'month' check (interval in ('week', 'month', 'quarter', 'year')),
  interval_count integer not null default 1 check (interval_count > 0),
  started_on date not null default current_date,
  current_period_start date,
  current_period_end date,
  next_billing_date date,
  cancelled_at timestamptz,
  external_reference text,
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    current_period_end is null
    or current_period_start is null
    or current_period_end >= current_period_start
  )
);

create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  activity_type text not null
    check (activity_type in ('call', 'email', 'meeting', 'task', 'note', 'status_change', 'system', 'other')),
  subject text not null check (btrim(subject) <> ''),
  body text,
  company_id uuid references public.companies(id) on delete set null,
  contact_id uuid references public.contacts(id) on delete set null,
  deal_id uuid references public.deals(id) on delete set null,
  project_id uuid references public.client_projects(id) on delete set null,
  lead_id uuid references public.leads(id) on delete set null,
  task_id uuid references public.tasks(id) on delete set null,
  actor_id uuid references public.profiles(id) on delete set null,
  occurred_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  check (
    company_id is not null or contact_id is not null or deal_id is not null
    or project_id is not null or lead_id is not null or task_id is not null
  )
);

create table if not exists public.notes (
