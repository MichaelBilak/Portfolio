create or replace function public.hq_set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'companies', 'contacts', 'products', 'deals', 'client_projects',
    'project_milestones', 'invoices', 'payments', 'subscriptions', 'notes'
  ]
  loop
    execute format('drop trigger if exists hq_set_updated_at on public.%I', table_name);
    execute format(
      'create trigger hq_set_updated_at before update on public.%I
       for each row execute function public.hq_set_updated_at()',
      table_name
    );
  end loop;
end;
$$;

create or replace function public.prevent_activity_mutation()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  -- Permit nested FK actions while rejecting direct edits/deletes.
  if pg_trigger_depth() > 1 then
    if tg_op = 'UPDATE' then
      return new;
    end if;
    return old;
  end if;
  raise exception 'activities is append-only';
end;
$$;

drop trigger if exists activities_append_only on public.activities;
create trigger activities_append_only
before update or delete on public.activities
for each row execute function public.prevent_activity_mutation();

create or replace function public.convert_lead_to_deal(
  p_lead_id uuid,
  p_actor_id uuid default null,
  p_title text default null
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  source_lead public.leads%rowtype;
  company_uuid uuid;
  contact_uuid uuid;
  deal_uuid uuid;
begin
  select * into source_lead
  from public.leads
  where id = p_lead_id
  for update;

  if not found then
    raise exception 'Lead % not found', p_lead_id using errcode = 'P0002';
  end if;

  if source_lead.converted_deal_id is not null then
    return source_lead.converted_deal_id;
  end if;

  company_uuid := source_lead.company_id;
  if company_uuid is null and nullif(btrim(coalesce(source_lead.business_name, '')), '') is not null then
    insert into public.companies (name, email, website, owner_id, created_by, metadata)
    values (
      btrim(source_lead.business_name),
      source_lead.email,
      source_lead.site_url,
      source_lead.assignee_id,
      p_actor_id,
      jsonb_build_object('source_lead_id', source_lead.id)
    )
    returning id into company_uuid;
  end if;

  contact_uuid := source_lead.contact_id;
  if contact_uuid is null and (
    nullif(btrim(coalesce(source_lead.full_name, '')), '') is not null
    or nullif(btrim(coalesce(source_lead.email, '')), '') is not null
  ) then
    insert into public.contacts (
      company_id, first_name, email, is_primary, created_by, metadata
    )
    values (
      company_uuid,
      nullif(btrim(source_lead.full_name), ''),
      source_lead.email,
      true,
      p_actor_id,
      jsonb_build_object('source_lead_id', source_lead.id)
    )
    returning id into contact_uuid;
  end if;

  insert into public.deals (
    company_id, primary_contact_id, lead_id, title, value, currency,
    owner_id, source, notes, created_by, metadata
  )
  values (
    company_uuid,
    contact_uuid,
    source_lead.id,
    coalesce(
      nullif(btrim(p_title), ''),
      nullif(btrim(source_lead.business_name), ''),
      nullif(btrim(source_lead.full_name), ''),
      'Lead ' || source_lead.id::text
    ),
    coalesce(source_lead.estimated_value, 0),
    source_lead.currency,
    source_lead.assignee_id,
    source_lead.source,
    source_lead.brief,
    p_actor_id,
    jsonb_build_object('source_lead_id', source_lead.id)
  )
  returning id into deal_uuid;

  update public.leads
  set company_id = company_uuid,
      contact_id = contact_uuid,
      converted_deal_id = deal_uuid,
      converted_at = now(),
      status = 'converted',
      updated_at = now()
  where id = source_lead.id;

  insert into public.activities (
    activity_type, subject, company_id, contact_id, deal_id, lead_id, actor_id, metadata
  )
  values (
    'system', 'Lead converted to deal', company_uuid, contact_uuid,
    deal_uuid, source_lead.id, p_actor_id, jsonb_build_object('conversion', 'lead_to_deal')
  );

  return deal_uuid;
end;
$$;

create or replace function public.convert_won_deal_to_project(
  p_deal_id uuid,
  p_actor_id uuid default null,
  p_name text default null
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  source_deal public.deals%rowtype;
  existing_project_id uuid;
  project_uuid uuid;
begin
  select * into source_deal
  from public.deals
  where id = p_deal_id
  for update;

  if not found then
    raise exception 'Deal % not found', p_deal_id using errcode = 'P0002';
  end if;

  select id into existing_project_id
  from public.client_projects
  where deal_id = source_deal.id;

  if existing_project_id is not null then
    return existing_project_id;
  end if;

  if source_deal.status <> 'won' or source_deal.stage <> 'won' then
    raise exception 'Deal % must be won before project conversion', p_deal_id
      using errcode = '23514';
  end if;

  insert into public.client_projects (
    deal_id, company_id, primary_contact_id, product_id, name, status, owner_id,
    start_date, budget, sold_price, currency, description, created_by, metadata
  )
  values (
    source_deal.id,
    source_deal.company_id,
    source_deal.primary_contact_id,
    source_deal.product_id,
    coalesce(nullif(btrim(p_name), ''), source_deal.title),
    'planned',
    source_deal.owner_id,
    current_date,
    source_deal.value,
    source_deal.value,
    source_deal.currency,
    source_deal.notes,
    p_actor_id,
    jsonb_build_object('source_deal_id', source_deal.id)
  )
  returning id into project_uuid;

  insert into public.activities (
    activity_type, subject, company_id, contact_id, deal_id, project_id, actor_id, metadata
  )
  values (
    'system', 'Won deal converted to project', source_deal.company_id,
    source_deal.primary_contact_id, source_deal.id, project_uuid, p_actor_id,
    jsonb_build_object('conversion', 'won_deal_to_project')
  );

  return project_uuid;
end;
$$;

create or replace function public.hq_dashboard_summary(
  p_from date default date_trunc('month', current_date)::date,
  p_to date default current_date
)
returns jsonb
language sql
stable
set search_path = public
as $$
  with params as (
    select least(p_from, p_to) as date_from, greatest(p_from, p_to) as date_to
  ),
  pipeline as (
    select
      count(*) filter (where d.status = 'open')::bigint as open_deals,
      coalesce(sum(d.value) filter (where d.status = 'open'), 0)::numeric as pipeline_value,
      coalesce(
        sum(d.value * d.probability::numeric / 100) filter (where d.status = 'open'),
        0
      )::numeric as weighted_pipeline,
      coalesce(
        sum(d.value) filter (
          where d.status = 'won'
            and d.closed_at::date between p.date_from and p.date_to
        ),
        0
      )::numeric as won_value
    from public.deals d cross join params p
  ),
  delivery as (
    select
      count(*) filter (where status in ('planned', 'discovery', 'design', 'development', 'testing', 'waiting_client', 'launch', 'paused'))::bigint as open_projects,
      count(*) filter (where health in ('yellow', 'red'))::bigint as unhealthy_projects,
      count(*) filter (
        where target_date < current_date and status not in ('completed', 'cancelled')
      )::bigint as overdue_projects
    from public.client_projects
  ),
  finance as (
    select
      coalesce(sum(total), 0)::numeric as invoiced_value,
      coalesce(sum(amount_paid), 0)::numeric as invoice_paid_value,
      coalesce(sum(total - amount_paid) filter (
        where status in ('sent', 'partially_paid', 'overdue')
      ), 0)::numeric as receivables
    from public.invoices i cross join params p
    where i.issue_date between p.date_from and p.date_to
  ),
  cash as (
    select coalesce(sum(amount) filter (where status = 'succeeded'), 0)::numeric as cash_collected
    from public.payments pay cross join params p
    where pay.paid_at::date between p.date_from and p.date_to
  ),
  recurring as (
    select coalesce(sum(
      case s.interval
        when 'week' then s.amount * 52 / (12 * s.interval_count)
        when 'month' then s.amount / s.interval_count
        when 'quarter' then s.amount / (3 * s.interval_count)
        when 'year' then s.amount / (12 * s.interval_count)
      end
    ) filter (where s.status in ('trialing', 'active', 'past_due')), 0)::numeric as mrr
    from public.subscriptions s
  )
  select jsonb_build_object(
    'from', p.date_from,
    'to', p.date_to,
    'openDeals', pipeline.open_deals,
    'pipelineValue', pipeline.pipeline_value,
    'weightedPipeline', pipeline.weighted_pipeline,
    'wonValue', pipeline.won_value,
    'openProjects', delivery.open_projects,
    'unhealthyProjects', delivery.unhealthy_projects,
    'overdueProjects', delivery.overdue_projects,
    'invoicedValue', finance.invoiced_value,
    'invoicePaidValue', finance.invoice_paid_value,
    'receivables', finance.receivables,
    'cashCollected', cash.cash_collected,
    'mrr', recurring.mrr
  )
  from params p
  cross join pipeline
  cross join delivery
  cross join finance
  cross join cash
  cross join recurring;
$$;

create or replace function public.record_invoice_payment(
  p_invoice_id uuid,
  p_amount numeric,
  p_currency text,
  p_method text default null,
  p_external_reference text default null,
  p_paid_at timestamptz default now(),
  p_metadata jsonb default '{}'::jsonb,
  p_created_by uuid default null
)
returns public.payments
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  source_invoice public.invoices%rowtype;
  payment_row public.payments%rowtype;
  next_paid numeric(14,2);
begin
  if p_amount <= 0 then
    raise exception 'Payment amount must be positive' using errcode = '23514';
  end if;

  select * into source_invoice from public.invoices
  where id = p_invoice_id for update;
  if not found then
    raise exception 'Invoice % not found', p_invoice_id using errcode = 'P0002';
  end if;
  if source_invoice.status in ('cancelled', 'void') then
    raise exception 'Cancelled invoice cannot receive payments' using errcode = '23514';
  end if;
  if upper(p_currency) <> source_invoice.currency then
    raise exception 'Payment currency must match invoice currency' using errcode = '23514';
  end if;
  if p_amount > source_invoice.total - source_invoice.amount_paid then
    raise exception 'Payment exceeds invoice outstanding amount' using errcode = '23514';
  end if;

  insert into public.payments (
    invoice_id, company_id, amount, currency, status, method,
    external_reference, paid_at, metadata, created_by
  ) values (
    source_invoice.id, source_invoice.company_id, p_amount, source_invoice.currency,
    'succeeded', p_method, p_external_reference, coalesce(p_paid_at, now()),
    coalesce(p_metadata, '{}'::jsonb), p_created_by
  ) returning * into payment_row;

  next_paid := source_invoice.amount_paid + p_amount;
  update public.invoices
  set amount_paid = next_paid,
      status = case when next_paid >= total then 'paid' else 'partially_paid' end,
      updated_at = now()
  where id = source_invoice.id;

  insert into public.activities (
    activity_type, subject, body, company_id, actor_id, occurred_at, metadata
  ) values (
    'system', 'Payment received', source_invoice.invoice_number,
    source_invoice.company_id, p_created_by, coalesce(p_paid_at, now()),
    jsonb_build_object('invoiceId', source_invoice.id, 'paymentId', payment_row.id, 'amount', p_amount)
  );

  return payment_row;
end;
$$;

