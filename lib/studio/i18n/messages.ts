export type StudioLocale = "ru" | "en";

export function resolveStudioLocale(value?: string | null): StudioLocale {
  return value === "en" ? "en" : "ru";
}

export function studioDateLocale(locale: StudioLocale) {
  return locale === "ru" ? "ru-RU" : "en-GB";
}

export function formatStudioDate(
  value: string | Date | null | undefined,
  locale: StudioLocale,
  withTime = false,
) {
  if (!value) return "—";
  const parsed = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(parsed.valueOf())) return String(value);
  return parsed.toLocaleString(
    studioDateLocale(locale),
    withTime
      ? { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" }
      : { day: "2-digit", month: "short", year: "numeric" },
  );
}

