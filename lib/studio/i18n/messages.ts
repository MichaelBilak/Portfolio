export const studioMessages = { ru, en } as const;
export type StudioMessageKey = MessageKey;

export type StudioVars = Record<string, string | number>;

export function translateStudio(
  locale: StudioLocale,
  key: StudioMessageKey,
  vars?: StudioVars,
) {
  let text = studioMessages[locale][key] || studioMessages.ru[key] || key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function createStudioTranslator(locale: StudioLocale) {
  return (key: StudioMessageKey, vars?: StudioVars) => translateStudio(locale, key, vars);
}

export function labelStatus(locale: StudioLocale, status: string) {
  const key = `status.${status}` as StudioMessageKey;
  return key in studioMessages.ru ? translateStudio(locale, key) : status.replaceAll("_", " ");
}

export function labelPriority(locale: StudioLocale, priority: string) {
  const key = `priority.${priority}` as StudioMessageKey;
  return key in studioMessages.ru ? translateStudio(locale, key) : priority;
}

export function labelLang(locale: StudioLocale, code: string) {
  const key = `lang.${code}` as StudioMessageKey;
  return key in studioMessages.ru ? translateStudio(locale, key) : code;
}

export function fieldLabel(locale: StudioLocale, fieldKey: string) {
  const key = `field.${fieldKey}` as StudioMessageKey;
  if (key in studioMessages.ru) return translateStudio(locale, key);
  return fieldKey
    .replace(/_i18n$/, locale === "ru" ? " переводы" : " translations")
    .replace(/_/g, " ")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/^./, (letter) => letter.toUpperCase());
}

